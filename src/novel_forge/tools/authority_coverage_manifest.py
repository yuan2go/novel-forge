"""Generate the deterministic authority-coverage baseline from Python ASTs."""
from __future__ import annotations

import ast
import hashlib
import json
import subprocess
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

GENERATOR_VERSION = "1.0.0"
SCAN_RULES = ("localstorage_import", "localstorage_constructor", "json_asset_method", "postgres_sync", "fallback", "external_call", "direct_runner")
LOCAL_METHODS = {"write_asset", "write_asset_auto", "write_json", "read_json", "read_asset", "list_json", "latest"}
AUTHORITY_WRITES = {"write_asset", "write_asset_auto", "write_json"}
EXTERNAL_CALLS = {"publish", "upload", "request", "post", "send", "run_model", "complete"}
FAMILIES = ("production", "workflow", "agent", "review", "revision", "publishing", "canon", "context", "quality", "source", "knowledge", "feedback", "project_lifecycle", "policy", "portfolio", "ops")


def operation_catalog() -> list[dict[str, Any]]:
    """Return the complete enabled-capability catalog used for Task 0 mapping."""
    names = {
        "production": ("topic.generate", "world.generate", "character.generate", "outline.generate", "chapter_plan.generate", "draft.generate", "chapter.export"),
        "workflow": ("start", "resume", "pause", "cancel", "recover"),
        "agent": ("dispatch", "retry", "recover", "dead_letter.replay"),
        "review": ("run", "resolve_issue"), "revision": ("apply",),
        "publishing": ("prepare_release", "submit", "receipt.record", "retract"),
        "canon": ("update", "character_state.update", "foreshadow_state.update", "recap.writeback"),
        "context": ("build", "compress", "approve", "invalidate"),
        "quality": ("evaluate", "run_completion_gate", "gate.resolve"),
        "source": ("import", "refresh", "quarantine", "release_quarantine"),
        "knowledge": ("card.create", "rule.create", "template.create", "pack.build", "weight.apply", "rebuild"),
        "feedback": ("import", "cluster", "patch.approve", "patch.apply"),
        "project_lifecycle": ("create", "clone", "pause", "resume", "archive", "delete"),
        "policy": ("bundle.apply", "provider.update", "budget.update"),
        "portfolio": ("priority.apply", "allocation.apply"),
        "ops": ("reindex", "reconcile", "migration.validate", "repair.apply"),
    }
    catalog: list[dict[str, Any]] = []
    for family in FAMILIES:
        for suffix in names[family]:
            name = f"{family}.{suffix}"
            catalog.append({
                "name": name, "family": family, "command_schema": f"{name}.command.v1", "result_schema": f"{name}.result.v1",
                "handler": f"novel_forge.modules.command_kernel.handlers.{family}", "execution_mode": "external" if family in {"publishing", "source", "production"} else "transactional",
                "permissions": [name], "approval_policy": "definition_policy", "idempotency_scope": "project:operation",
                "concurrency_key": "project:{project_id}:{operation}", "attempt_retry_timeout_policy": "definition_default_v1",
                "external_capabilities": [], "cancellation_policy": "controlled", "compensation_policy": "definition_default",
                "completion_contract": "completion_contract.v1", "input_output_evidence": ["trace", "audit", "outbox"],
                "current_entrypoints": [], "migration_status": "planned",
            })
    legacy = {"workflow.start": "workflow.execute", "agent.dispatch": "agent.dispatch", "review.run": "loop.run", "production.draft.generate": "chapter_production.start"}
    for item in catalog:
        if item["name"] in legacy:
            item["legacy_characterization"] = legacy[item["name"]]
    return catalog


def write_operation_catalog(repo_root: str | Path, json_output: str | Path, markdown_output: str | Path) -> list[dict[str, Any]]:
    catalog = operation_catalog()
    Path(json_output).write_text(json.dumps({"schema_version": "1.0.0", "git_sha": _git_sha(Path(repo_root)), "definitions": catalog}, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    rows = ["# PostgreSQL OperationDefinition Catalog", "", "Generated by authority coverage tooling.", "", "| Name | Family | Mode | Migration |", "|---|---|---|---|"]
    rows.extend(f"| `{item['name']}` | `{item['family']}` | `{item['execution_mode']}` | `{item['migration_status']}` |" for item in catalog)
    Path(markdown_output).write_text("\n".join(rows) + "\n", encoding="utf-8")
    return catalog


def write_legacy_actions(manifest: dict[str, Any], output: str | Path) -> dict[str, Any]:
    """Turn every detected legacy dependency into a file/symbol-level action."""
    actions = []
    for finding in manifest["findings"]:
        usage = finding["usage_type"]
        action = "migration_only" if usage == "sync" else "replace" if finding["side_effect"] else "retain"
        if finding["path"].startswith("tests/"):
            action = "fixture_only"
        actions.append({**finding, "action": action, "rationale": finding["evidence"]})
    payload = {"schema_version": "1.0.0", "git_sha": manifest["git_sha"], "baseline_hash": manifest["artifact_hash"], "actions": actions}
    payload["artifact_hash"] = _hash(payload)
    Path(output).write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return payload


def build_manifest(repo_root: str | Path, *, generated_at: str | None = None) -> dict[str, Any]:
    root = Path(repo_root).resolve()
    findings: list[dict[str, Any]] = []
    paths = sorted((root / "src" / "novel_forge").rglob("*.py"))
    for path in paths:
        findings.extend(_scan_file(root, path))
    findings.sort(key=lambda item: (item["path"], item["line"], item["symbol"], item["dependency"]))
    counts = Counter(item["usage_type"] for item in findings)
    payload = {
        "schema_version": "1.0.0",
        "generator_version": GENERATOR_VERSION,
        "git_sha": _git_sha(root),
        "generated_at": generated_at or datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "scan_rules": list(SCAN_RULES),
        "file_count": len(paths),
        "finding_count": len(findings),
        "summary": {
            "files_with_findings": len({item["path"] for item in findings}),
            "symbols": len({(item["path"], item["line"], item["symbol"]) for item in findings}),
            "authority_write": counts["authority_write"],
            "authority_read": counts["authority_read"],
            "query": counts["query"],
            "fixture_test": sum(counts[key] for key in ("fixture", "test")),
            "unknown": counts["unknown"],
        },
        "findings": findings,
    }
    payload["artifact_hash"] = _hash(payload)
    return payload


def write_manifest(repo_root: str | Path, output: str | Path, *, generated_at: str | None = None) -> dict[str, Any]:
    manifest = build_manifest(repo_root, generated_at=generated_at)
    Path(output).write_text(json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def _scan_file(root: Path, path: Path) -> list[dict[str, Any]]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except SyntaxError:
        return []
    visitor = _Visitor(root, path)
    visitor.visit(tree)
    return visitor.findings


class _Visitor(ast.NodeVisitor):
    def __init__(self, root: Path, path: Path) -> None:
        self.root, self.path = root, path
        self.local_names: set[str] = set()
        self.findings: list[dict[str, Any]] = []
        self.scope = "<module>"

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.module == "novel_forge.storage.local":
            for name in node.names:
                if name.name == "LocalStorage":
                    local = name.asname or name.name
                    self.local_names.add(local)
                    self._add(node, local, "LocalStorage", "authority_read", False, "localstorage")
        self.generic_visit(node)

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        before, self.scope = self.scope, node.name
        self.generic_visit(node)
        self.scope = before

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_Call(self, node: ast.Call) -> None:
        name = _call_name(node.func)
        if name in self.local_names or name == "LocalStorage":
            self._add(node, name, "LocalStorage", "authority_read", False, "localstorage")
        elif name in LOCAL_METHODS:
            write = name in AUTHORITY_WRITES
            self._add(node, name, f"LocalStorage.{name}", "authority_write" if write else "authority_read", write, "localstorage")
        elif name in {"sync_from_local", "sync_asset", "sync_postgres_after_task", "postgres_sync"}:
            self._add(node, name, "postgres_sync", "sync", True, "mixed")
        elif "fallback" in name.lower():
            self._add(node, name, "fallback", "fallback", False, "mixed")
        elif name in {"dispatch_chapter_production", "execute_workflow", "dispatch_agent_run", "run_loop"}:
            self._add(node, name, "legacy_runner", "unknown", True, "mixed")
        elif name in EXTERNAL_CALLS and self.path.parts[-3:-1] not in [("tests", "unit")]:
            self._add(node, name, "external_call", "external_effect", True, "none")
        self.generic_visit(node)

    def _add(self, node: ast.AST, symbol: str, dependency: str, usage_type: str, side_effect: bool, authority: str) -> None:
        entrypoint = _entrypoint_kind(self.path)
        self.findings.append({
            "path": str(self.path.relative_to(self.root)),
            "line": int(getattr(node, "lineno", 0)),
            "symbol": symbol,
            "dependency": dependency,
            "usage_type": usage_type,
            "side_effect": side_effect,
            "current_authority": authority,
            "entrypoint_kind": entrypoint,
            "target_operation_definition": _target_operation(self.path, usage_type, side_effect),
            "target_handler": "",
            "target_aggregate": "",
            "target_repository": "",
            "target_query_path": "postgres_write_model" if usage_type == "authority_read" else "",
            "external_effect_type": "external.dispatch" if usage_type == "external_effect" else "",
            "migration_action": "replace" if side_effect or dependency == "LocalStorage" else "review",
            "status": "unmapped",
            "evidence": f"{dependency} detected by {GENERATOR_VERSION}",
        })


def _call_name(node: ast.AST) -> str:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return ""


def _entrypoint_kind(path: Path) -> str:
    value = str(path).replace("\\", "/")
    if "/api/routers/" in value: return "api"
    if "/workers/" in value: return "worker"
    if "/cli/" in value: return "cli"
    if "/agent_scheduler/" in value: return "scheduler"
    if "/state_bus/" in value: return "consumer"
    return "domain_service" if "/modules/" in value else "internal"


def _target_operation(path: Path, usage_type: str, side_effect: bool) -> str:
    if not side_effect: return ""
    text = str(path)
    for family, marker in (("publishing", "publish"), ("review", "review"), ("revision", "revision"), ("context", "context"), ("knowledge", "mkaos"), ("source", "source"), ("workflow", "workflow"), ("agent", "agent"), ("canon", "canon"), ("quality", "quality"), ("feedback", "feedback"), ("project_lifecycle", "project")):
        if marker in text: return f"{family}.unmapped"
    return "ops.unmapped"


def _hash(payload: dict[str, Any]) -> str:
    canonical = {key: value for key, value in payload.items() if key != "artifact_hash"}
    return "sha256:" + hashlib.sha256(json.dumps(canonical, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode()).hexdigest()


def _git_sha(root: Path) -> str:
    try:
        # Bind the baseline to the scanned source tree. A checked-in report
        # changes the commit SHA that contains it, whereas HEAD:src is stable
        # across documentation-only commits and still invalidates on source
        # changes that can alter coverage.
        return subprocess.check_output(["git", "rev-parse", "HEAD:src"], cwd=root, text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    write_manifest(args.repo_root, args.output)
