from __future__ import annotations

OPERATION_TRANSITIONS = {
    "ADMITTED": {"WAITING_APPROVAL", "READY", "FAILED_FINAL"},
    "WAITING_APPROVAL": {"READY", "CANCELLED", "FAILED_FINAL"},
    "READY": {"EXECUTING", "WAITING_CHILDREN", "CANCELLATION_REQUESTED"},
    "EXECUTING": {"WAITING_EXTERNAL_RESULT", "WAITING_GATE", "WAITING_CHILDREN", "SUCCEEDED", "FAILED_RETRYABLE", "FAILED_FINAL", "CANCELLATION_REQUESTED"},
    "CANCELLATION_REQUESTED": {"CANCELLED", "RECONCILIATION_REQUIRED", "COMPENSATION_REQUIRED"},
    "COMPENSATION_REQUIRED": {"COMPENSATING", "RECONCILIATION_REQUIRED", "FAILED_FINAL"},
    "COMPENSATING": {"COMPENSATED", "COMPENSATION_FAILED", "RECONCILIATION_REQUIRED"},
    "FAILED_RETRYABLE": {"READY", "FAILED_FINAL", "DEAD_LETTER", "CANCELLATION_REQUESTED"},
}


def require_transition(current: str, target: str) -> None:
    if target not in OPERATION_TRANSITIONS.get(current, set()):
        raise ValueError(f"invalid operation transition: {current} -> {target}")
